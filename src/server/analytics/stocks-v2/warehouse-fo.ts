/**
 * Маппинг названий ФО из WB API (raw_api_region_sales.fo_name) на наш канон.
 * WB API может прислать «Южный» и «Северо-Кавказский» отдельно — объединяем.
 */
export function normalizeWbFoName(rawFo: string): FederalDistrict {
  const lower = (rawFo || '').toLowerCase().trim();
  if (lower.includes('централь')) return 'Центральный';
  if (lower.includes('северо-запад') || lower.includes('северозапад')) return 'Северо-Западный';
  if (lower.includes('южн') || lower.includes('кавказ')) return 'Юг (ЮФО+СКФО)';
  if (lower.includes('приволж')) return 'Приволжский';
  if (lower.includes('ураль')) return 'Уральский';
  if (lower.includes('сибир')) return 'Сибирский';
  if (lower.includes('дальневост')) return 'Дальневосточный';
  if (
    lower.includes('казахст') || lower.includes('белар') || lower.includes('армен') ||
    lower.includes('киргиз') || lower.includes('узбек') || lower.includes('азерб') ||
    lower.includes('грузи')
  ) return 'СНГ / Зарубеж';
  return 'Другие';
}
