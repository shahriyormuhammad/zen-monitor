const cache = new Map<string, FederalDistrict>();

/**
 * Returns the federal district that a WB warehouse name belongs to.
 * Case-insensitive, ignores trailing «WB», numeric suffixes etc.
 */
export function resolveWarehouseFo(rawName: string): FederalDistrict {
  if (!rawName) return 'Другие';
  const cached = cache.get(rawName);
  if (cached) return cached;
  const lower = rawName.toLowerCase().trim();
  if (VIRTUAL.some((v) => lower.includes(v))) {
    cache.set(rawName, 'Виртуальный');
    return 'Виртуальный';
  }
  for (const rule of RULES) {
    if (rule.triggers.some((t) => lower.includes(t))) {
      cache.set(rawName, rule.fo);
      return rule.fo;
    }
  }
  cache.set(rawName, 'Другие');
  return 'Другие';
}

